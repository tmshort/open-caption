// Help viewer: topic list, search, and rendered topics. Works offline (all content is served by this program).
(() => {
  'use strict';
  if (window.OC_UNSUPPORTED) return; // compat.js has already shown the "too old" message
  const $ = (id) => document.getElementById(id);
  const params = new URLSearchParams(location.search);
  const role = params.get('role') === 'operator' ? 'operator' : 'admin';
  if (params.has('embed')) document.body.classList.add('embed');
  let topics = [];
  const LANG = '?lang=' + OCI18n.lang;

  async function get(path) { const r = await fetch(path); if (r.status === 401 || r.status === 403) throw new Error('login'); return r; }

  function listTopics(items, title) {
    const h = document.createElement('h2'); h.textContent = __(title);
    return [h, ...items.map((t) => {
      const a = document.createElement('a');
      a.href = '#' + t.id; a.dataset.topic = t.id; a.textContent = t.title;
      if (t.snippet) { const s = document.createElement('span'); s.className = 'snip'; s.textContent = t.snippet; a.appendChild(s); }
      return a;
    })];
  }

  function renderList(hits) {
    const nav = $('topics'); nav.replaceChildren();
    if (hits) { nav.append(...listTopics(hits.map((h) => h), hits.length ? 'Search results' : 'No matches')); return; }
    const mine = topics.filter((t) => t.role === role), other = topics.filter((t) => t.role !== role);
    nav.append(...listTopics(mine, role === 'admin' ? 'Setting up' : 'Running the show'), ...listTopics(other, role === 'admin' ? 'For the operator' : 'For whoever sets up'));
    mark();
  }
  function mark() { document.querySelectorAll('#topics a').forEach((a) => (a.dataset.topic === current ? a.setAttribute('aria-current', 'page') : a.removeAttribute('aria-current'))); }

  let current = '';
  async function show(id, anchor) {
    const t = topics.find((x) => x.id === id) || topics.find((x) => x.role === role) || topics[0];
    if (!t) return;
    current = t.id;
    const r = await get('/help/' + t.id + LANG);
    const doc = $('doc');
    doc.innerHTML = await r.text(); // generated by the server from embedded Markdown; all text is escaped
    doc.querySelectorAll('pre').forEach((pre) => {
      const code = pre.innerText.trimEnd();
      const b = document.createElement('button'); b.type = 'button'; b.textContent = __('Copy');
      b.addEventListener('click', async () => { try { await navigator.clipboard.writeText(code); b.textContent = __('Copied'); setTimeout(() => (b.textContent = __('Copy')), 1500); } catch (e) { b.textContent = __('Select and copy'); } });
      pre.appendChild(b);
    });
    doc.scrollTop = 0; mark();
    if (anchor) scrollToAnchor(anchor);
    if (location.hash.slice(1) !== t.id) history.replaceState(null, '', '#' + t.id + location.search.replace(/^\?/, '?'));
  }

  function scrollToAnchor(id) {
    const el = $('doc').querySelector('[id="' + id.replace(/"/g, '') + '"]');
    if (el) el.scrollIntoView({ block: 'start' });
  }
  document.addEventListener('click', (e) => {
    const a = e.target.closest('a[data-topic], a[data-anchor]'); if (!a) return;
    e.preventDefault();
    if (a.dataset.topic && a.dataset.topic !== current) show(a.dataset.topic, a.dataset.anchor);
    else if (a.dataset.anchor) scrollToAnchor(a.dataset.anchor);
    else if (a.dataset.topic) show(a.dataset.topic);
  });
  let timer;
  $('q').addEventListener('input', () => {
    clearTimeout(timer);
    timer = setTimeout(async () => {
      const q = $('q').value.trim();
      if (!q) { renderList(); return; }
      const r = await get('/api/help/search' + LANG + '&q=' + encodeURIComponent(q));
      renderList((await r.json()).hits);
    }, 200);
  });
  document.addEventListener('keydown', (e) => { if (e.key === 'Escape' && window.parent !== window) window.parent.postMessage({ type: 'help-close' }, location.origin); });

  OCI18n.apply();
  if (!params.has('embed')) $('side').insertBefore(OCI18n.picker(), $('q'));
  (async () => {
    try {
      const r = await get('/api/help/topics' + LANG);
      topics = (await r.json()).topics;
      $('app').hidden = false;
      renderList();
      await show(params.get('topic') || location.hash.slice(1));
    } catch (e) { $('login').hidden = false; }
  })();
})();
