# Runs `go <command> ...` with the DNS providers for automatic certificates (ACME DNS-01) that you choose built in.
#
#   tools/acme-go.sh "<providers>" build -o bin/open-caption ./cmd/open-caption
#
# <providers> is what the Makefile calls ACME_PROVIDERS:
#   (empty) or "cloudflare godaddy easydns"   the default: the plain build, nothing extra needed
#   none                                      ACME left out entirely (smallest binary)
#   all                                       every provider the lego library has (a much larger binary)
#   one or more lego provider names           exactly those, e.g. "easydns route53"; names are the directory names in
#                                             github.com/go-acme/lego/v4/providers/dns
#
# For a custom list or "all" it writes internal/acme/zz_providers_gen.go (ignored by git, removed when done) that imports
# them. A provider that is not in the default list needs modules go.mod does not list, so the build then uses a copy of
# go.mod and go.sum (go.acme.mod / go.acme.sum, also ignored) that Go fills in: the real go.mod stays small. That needs internet.
set -e
cd "$(dirname "$0")/.."
list=$(printf '%s' "$1" | tr ',A-Z' ' a-z'); shift
cmd="$1"; shift
default="cloudflare easydns godaddy"
set -- $list "--" "$@"   # the provider names, then --, then the rest of the go arguments
names=""
while [ "$1" != "--" ]; do names="$names $1"; shift; done
shift
set -- "$cmd" "$@"       # back to: <go command> <its arguments>
names=$(printf '%s\n' $names | sort -u | tr '\n' ' ' | sed 's/ $//')
[ -z "$names" ] && names="$default"

run() { sub="$1"; shift; exec go "$sub" "$@"; }   # (never returns)
gen=internal/acme/zz_providers_gen.go
cleanup() { rm -f "$gen" go.acme.mod go.acme.sum; }

case "$names" in
  none) sub="$1"; shift; run "$sub" -tags=acme_off "$@" ;;
  "$default") run "$@" ;;
esac

trap cleanup EXIT INT TERM
legodir=$(go list -m -f '{{.Dir}}' github.com/go-acme/lego/v4)
extra=0
{
  echo "//go:build acme_custom"; echo; echo "// Code generated by tools/acme-go.sh; DO NOT EDIT."; echo
  echo "package acme"; echo; echo "import ("
  echo '	"github.com/go-acme/lego/v4/challenge"'
  if [ "$names" = "all" ]; then echo '	"github.com/go-acme/lego/v4/providers/dns"'; extra=1
  else
    for p in $names; do
      if [ ! -d "$legodir/providers/dns/$p" ]; then
        echo "tools/acme-go.sh: unknown DNS provider '$p' (see the directories in $legodir/providers/dns). Or use 'all' or 'none'." >&2; exit 1
      fi
      echo "	p_$p \"github.com/go-acme/lego/v4/providers/dns/$p\""
      case " $default " in *" $p "*) ;; *) extra=1;; esac
    done
  fi
  echo ")"; echo
  echo "var _ challenge.Provider"; echo
  echo "func init() {"
  if [ "$names" = "all" ]; then echo "	lookupAny = dns.NewDNSChallengeProviderByName"
  else for p in $names; do echo "	register(\"$p\", func() (challenge.Provider, error) { return p_$p.NewDNSProvider() })"; done
  fi
  echo "}"
} > "$gen"
gofmt -w "$gen"
sub="$1"; shift
if [ $extra -eq 1 ]; then
  cp go.mod go.acme.mod; cp go.sum go.acme.sum
  go "$sub" -tags=acme_custom -mod=mod -modfile=go.acme.mod "$@"
else
  go "$sub" -tags=acme_custom "$@"
fi
